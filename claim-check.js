/**
 * **"사용자가 부탁한 일이 도구를 필요로 했나."**
 *
 * ── 왜 이게 따로 필요한가 (2026-08-20) ───────────────────────────────
 * 위 방식은 **두뇌의 말**에서 출발한다. 그래서 이 파일 맨 위에 적어둔 한계가 있다 —
 * *"거짓말은 잡고 **빠뜨림은 못 잡는다**"*. 실제로 그 구멍으로 사고가 났다.
 *
 *   사용자  "바탕화면에 폴더 만들어줘"
 *   codex   "권한이 읽기 전용이라 못 만듭니다"        ← 도구 호출 0. **시도한 적 없다**
 *   사용자  "허용할게 너가 만들어봐"
 *   codex   "시도했는데 차단됐습니다"                  ← 도구 호출 0. 여전히 없다
 *
 * *"차단됐습니다"* 는 **실패 주장**이라 완료 어미 그물에 안 걸렸다. 검사가 아예 안 돌았다.
 * 낱말을 더 넣는 건 땜빵이다 — 이미 두 번 샜고(`해봤어요` 누락 → 이번엔 실패 주장 통째),
 * *"불가능합니다"·"권한 밖입니다"* 로 또 샌다.
 *
 * → **판단축을 바꾼다.** 두뇌가 뭐라고 했는지가 아니라
 *   **사용자가 무엇을 부탁했는지** + **도구를 부르기라도 했는지**로 본다.
 *   업계 원칙과 같은 방향이다 — *"런타임이 진실의 원천이지 LLM 의 텍스트가 아니다."*
 *
 * ── 실측 (codex / GPT 구독, 2026-08-21) ──────────────────────────────
 *   1차 26건 26/26 · 2차(적대적) 확정 14/14 · 3차(맥락 쌍) 12/12
 *   놓침 0 · 헛것 0 · 지연 중앙값 ≈5초 · 프롬프트 ≈550토큰(말 기준 방식의 1/4)
 *   ⚠️ 문제·정답을 내가 만든 표본이다. 실사용 분포는 다를 수 있다.
 *
 * ── 왜 직전 턴을 같이 보나 ───────────────────────────────────────────
 * 맥락 없이 요청만 보면 *"응 해줘"·"그래"·"한번 더 해봐"* 가 **전부 need=false** 로 나왔다(실측).
 * 직전 턴이 *"폴더 만들어드릴까요?"* 였다면 사고가 그대로 재발한다.
 * 지시대명사는 거의 언제나 **바로 앞**을 가리키므로 한 턴만 붙인다. 더 넣으면 비용만 늘고 판정이 흐려진다.
 */
/**
 * ★**기억 조회(recall)는 여기서 판정하지 않는다** (2026-08-21 결정).
 *
 * 갈래마다 이 판정의 성질이 다르다.
 *   · 파일·예약·셸·웹검색 = **요청만으로 답이 정해진다.** 폴더를 만들려면 대화에 무슨 말이 오갔든
 *     무조건 도구가 필요하다. 대화 내용과 무관하다.
 *   · **기억 조회 = 대화 내용에 따라 답이 달라진다.** 같은 *"저번에 그 얘기"* 라도
 *     그 내용이 이번 턴 프롬프트(최근 20,000토큰) 안에 있으면 도구가 **불필요**하고,
 *     밖으로 밀려났으면 **필요**하다. **요청만 보는 이 판정기로는 결정할 수 없다.**
 *
 * 성질이 다른 것을 같은 통에 넣었던 게 잘못이었다. 그래서 답을 못 내고
 * *"아까/방금 → 지금 대화, 어제/저번에 → 지난 대화"* 라는 **낱말 목록으로 메웠다.**
 * 낱말은 무한하니 계속 샌다. 더 나쁘게는 **대화량이 적어 지난주 얘기가 창 안에 멀쩡히 있어도**
 * *"지난주"* 라는 말만 보고 `search_memory` 를 부르게 했다 — 헛수고다.
 *
 * 억지로 판정하려면 판정기가 **프롬프트 내용을 다시 읽어야** 한다. 두뇌가 이미 읽은 것을
 * 한 번 더 읽는 것이고, **매 턴 도는 검사에 붙일 비용이 아니다.**
 *
 * ★그리고 실측이 이미 답을 주고 있었다 — 기억 조회 갈래는 **자발 3/3 · 3/3 · 3/3 · 5/5**,
 *   **탐지가 발동한 적이 0회**다. 두뇌가 알아서 다 불렀다. 판정기가 도울 일이 없는 갈래였다.
 *   반면 그걸 판정하려다 **잡담 턴을 6.6초 → 24.3초로 만들었다.** 얻는 것 없이 해만 있었다.
 *
 * ⚠️ **다시 넣지 마라.** 넣고 싶으면 위 두 가지를 먼저 뒤집어라 —
 *   ①요청만으로 판정 가능해졌는가 ②탐지가 실제로 값어치를 하는가(지금은 0회다).
 *   기억 조회를 두뇌가 놓치고 지어내는 경우는 **3차(완료 주장 대조)가 원래 잡던 자리**다.
 */
const NEED_TOOL_SYSTEM = `사용자가 방금 한 말이 **에이전트가 도구를 불러야 하는 일**인지 판정한다.

이 에이전트가 실제로 가진 도구
  file      파일·폴더 만들기/읽기/쓰기/목록/찾기
  schedule  알림·예약 걸기 / 목록 / 취소
  search    웹에서 찾아보기
  shell     프로그램·명령 실행
  other     스킬·MCP 설치, 파일 보내기, 작업 위임

도구가 **필요 없는** 것 — 여기서 true 를 내면 안 된다
  · 인사·잡담·감사·감탄
  · 의견·설명·번역·요약·계산을 **말로** 하는 것
  · **"할 수 있어?" "어떻게 해?"** — 가능 여부·방법을 묻는 것(직접 해달라는 게 아니다)
  · **현재 시각·날짜** — 이미 알고 있다. 그런 도구는 없다
  · **지금 이 대화에 이미 나온 내용** — 다시 말해주면 된다
  · **지난 대화·기억을 물어보는 것** — 여기서는 판정하지 않는다. **항상 false 로 둬라.**
  · 사용자가 자기 이야기를 들려주거나 **"기억해둬"** 라고 하는 것
    → 저장은 턴이 끝나면 **자동으로** 된다. 도구를 부를 필요가 없다

★짧은 대답("응", "그래", "해줘", "한번 더", "그거 말고")은 그것만으로 판정하지 말고
  [직전에 에이전트가 한 말]을 보고 **무엇을 승낙한 것인지** 판단한다.
  에이전트가 뭔가 해주겠다고 제안했고 사용자가 승낙했으면 → 그 일에 필요한 도구.

출력: JSON 한 줄만. 다른 말 금지.
{"need":true|false,"kind":"file|schedule|search|shell|other|none","query":""}

query 는 **kind 가 search 일 때만** 채운다. 사용자 말에서 **실제로 검색창에 넣을 말**만 뽑아라.
  "오늘 서울 날씨 검색해서 알려줘"        → "오늘 서울 날씨"
  "그거 좀 찾아봐" (앞턴: 전기차 보조금)   → "전기차 보조금"
  "요즘 환율 어때? 궁금해서"              → "원달러 환율"
부탁하는 말투("~해줘", "알려줘", "좀")는 빼라. 검색어가 안 잡히면 빈 문자열.`;

/** 실패하면 need:false — 검사가 대화를 막지 않는다(이 파일의 일관된 원칙). */
async function needsTool(userMessage, prevAssistant, generate) {
  const msg = String(userMessage || '').trim();
  if (!msg || typeof generate !== 'function') return { need: false, kind: 'none' };
  const prev = String(prevAssistant || '').trim().slice(0, 300);
  const user = prev
    ? `[직전에 에이전트가 한 말]
${prev}

[사용자가 방금 한 말]
${msg.slice(0, 500)}`
    : msg.slice(0, 500);
  let raw;
  //   ★tools:false 를 **명시한다.** 지금은 두뇌들이 opts.tools 참/거짓만 봐서 생략해도 안 붙지만,
  //     구독 두뇌는 이 값이 **MCP 설정을 실을지**까지 정한다. 판정 호출에 사용자의 MCP 가 실리면
  //     그것만으로 비용이 크고, 더 나쁘게는 **판정하다가 남의 캘린더를 부를 수 있다**(2026-08-06 N-11 사고).
  //     memory-post 도 같은 이유로 명시한다 — 관례를 따른다.
  try { raw = await generate(NEED_TOOL_SYSTEM, user, { tools: false, timeout: 20000, temperature: 0, maxTokens: 60 }); }
  catch (_) { return { need: false, kind: 'none' }; }
  const m = String(raw || '').match(/\{[\s\S]*?\}/);
  if (!m) return { need: false, kind: 'none' };
  try {
    const j = JSON.parse(m[0]);
    return { need: j.need === true, kind: String(j.kind || 'other'), query: String(j.query || '').trim() };
  } catch (_) { return { need: false, kind: 'none' }; }
}

// ── 3차: 대조 ───────────────────────────────────────────────────────────
/**
 * @returns {Promise<{suspect:boolean, claims:string[], calledTools:string[]}>}
 *   suspect=true 면 "말은 했는데 도구를 하나도 안 불렀다".
 */
async function check({ agentId, responseText, userMessage, prevAssistant, needResult, turnStartTs, generate }) {
  const empty = { suspect: false, reason: null, claims: [], kind: 'none', calledTools: [] };
  if (!agentId || !responseText || typeof generate !== 'function') return empty;

  // ── 1차 — 장부부터. 공짜다 ────────────────────────────────────────────
  //   ★`toolAttemptsSince` 다(성공만 주는 `toolCallsSince` 가 아니다).
  //     여기서 묻는 건 *"아예 시도조차 안 했나"* 이고, **막혀서 실패한 것도 시도**다.
  //     권한에 막힌 뒤 허용을 요청하는 건 **옳은 행동**이라 되돌리면 오탐이 된다.
  let attempted = [];
  try { attempted = storage.toolAttemptsSince(agentId, turnStartTs) || []; } catch (_) { attempted = []; }
  if (attempted.length) return { ...empty, calledTools: attempted };

  // ── 2차 — 요청 기준 (≈550토큰) ────────────────────────────────────────
  //   **사용자가 부탁한 일이 도구를 요했나.** 답변은 안 본다 —
  //   그래서 두뇌가 무슨 말로 둘러댔는지("차단됐습니다")와 **무관하게** 걸린다.
  //   ※ userMessage 를 안 넘긴 호출부는 이 단계를 건너뛴다(하위 호환).
  if (userMessage) {
    //   ★엔진이 턴 시작 때 **미리 띄워둔** 결과가 있으면 그걸 쓴다(기다리는 시간 0).
    //     없으면(다른 호출부·되돌림 2회차) 여기서 직접 판정한다.
    const need = needResult || await needsTool(userMessage, prevAssistant, generate);
    if (need.need) return { suspect: true, reason: 'request', claims: [], kind: need.kind, query: need.query || '', calledTools: [] };
  }

  // ── 3차 — 말 기준 (기존 방식, ≈2,000토큰) ─────────────────────────────
  //   2차를 통과했어도 여기가 남는다. **둘은 잡는 것이 다르다.**
  //     · 2차 = 사용자가 부탁했는데 **안 한 것**(빠뜨림·거짓 무능)
  //     · 3차 = 부탁하지도 않았는데 **했다고 하는 것**(자발적 완료 주장)
  //   3차가 비싸므로 공짜 낱말 필터를 앞에 그대로 둔다.
  if (!mayClaimCompletion(responseText)) return empty;
  const claims = await extractClaims(responseText, generate);
  if (!claims.length) return empty;
  return { suspect: true, reason: 'claim', claims, kind: 'none', calledTools: [] };
}

// ── 되돌림 문구 ─────────────────────────────────────────────────────────
/**
 * 두뇌에게 돌려줄 말. **"안 했어"만으로는 부족하다** — 도구가 아예 없는 상황이면
 * 두뇌는 또 말로 때운다. 그래서 두 가지를 반드시 같이 준다.
 *   ① 지금 쓸 수 있는 도구가 무엇인지 (또는 목록을 확인하라는 지시)
 *   ② **"없으면 못 한다고 말해도 된다"** — 이게 없으면 어떻게든 되려고 하다 또 지어낸다
 *
 * @param toolNames 우리가 넘긴 도구 이름들. 구독 두뇌는 CLI가 노출을 정해서 우리가 모른다
 *                  → 빈 배열이면 "네 목록을 확인하라"로 바꿔 말한다(그 답이 배선 끊김도 드러낸다).
 */
function buildNudge(claims, toolNames = []) {
  const list = Array.isArray(toolNames) && toolNames.length
    ? `지금 네가 쓸 수 있는 도구: ${toolNames.join(', ')}`
    : '먼저 네 도구 목록에 그런 도구가 있는지 확인해.';
  return '[시스템 확인]\n'
    + `방금 답에서 이걸 **해냈다고** 말했어: ${claims.map(c => `"${c}"`).join(', ')}\n`
    + '그런데 이번 턴에 **도구를 하나도 부르지 않았어.** 말로만 처리한 거야.\n'
    + `${list}\n`
    + '· 그 도구가 있으면 **지금 실제로 불러서** 하고, 그다음에 답해.\n'
    + '· 없으면 **"못 한다"고 사용자에게 솔직히 말해.** 못 하는 건 괜찮아. 한 척하는 게 문제야.\n'
    + '· 이 [시스템 확인] 자체는 사용자에게 언급하지 마.';
}

/**
 * 요청 기준(reason='request') 되돌림 — **말 기준과 문구가 달라야 한다.**
 *
 * 기존 문구는 *"이걸 해냈다고 말했잖아"* 로 시작한다. 그런데 여기서 잡히는 턴은
 * 대개 **해냈다고 말한 적이 없다.** *"권한이 없어 못 합니다"* 처럼 **못 한다고** 했다.
 * 그 상태에서 "했다고 말했잖아"라고 하면 두뇌가 부인하며 같은 말을 되풀이한다.
 *
 * ★한 문장이 핵심이다 — **"부르면 권한 요청이 뜬다. 안 부르면 요청조차 안 생긴다."**
 *   2026-08-20 사고가 정확히 그 고리였다: codex 가 권한이 없다고 **혼자 판단**해
 *   `make_dir` 을 안 불렀고 → 허용 요청이 안 생겼고 → 사용자의 *"허용할게"* 가 허공에 떴다.
 *   두뇌가 권한을 미리 짐작하는 것 자체가 틀렸다는 걸 알려줘야 고리가 끊긴다.
 */
function buildRequestNudge(kind, toolNames = [], userMessage = '') {
  const 갈래 = {
    file: '파일·폴더', schedule: '알림·예약', search: '웹 검색',
    shell: '명령 실행', other: '',
  }[kind] || '';
  // ★갈래에 맞는 도구를 **콕 집어** 준다.
   //   전엔 도구를 30개 통째로 나열했는데, 그 목록 안에서 두뇌가 "그런 건 없다"는 출구로 빠졌다
   //   (실측: 되돌림 2회를 다 쓰고도 PowerShell 명령을 안내했다).
   //   이름을 콕 집으면 "찾아봐"가 아니라 "이걸 불러"가 된다.
  const 후보 = {
    file: ['make_dir', 'write_file', 'list_files', 'read_file'],
    schedule: ['schedule_task', 'list_schedules', 'cancel_schedule'],
    search: ['web_search'],
    shell: ['run_shell', 'run_code'],
  }[kind] || [];
  const 가진것 = Array.isArray(toolNames) ? toolNames : [];
  //   ★이름을 **정확히 대조하면 안 된다.** 구독 두뇌에 넘기는 availableTools 는 이름이 아니라
  //     설명 문장이다 — "터미널 명령 실행(run_shell — 허용 폴더에서, 파괴적 명령 차단…)" 같은 식.
  //     처음엔 includes(t) 로 정확히 대조해서 **한 번도 안 맞았고**, 그 결과 아래 폴백으로 떨어져
  //     설명 19개가 통째로 실려 되돌림이 **1,631자**가 됐다(실측). 콕 집으려던 것과 정반대다.
  //     → 문장 **안에 이름이 들어 있는지**로 본다.
  const 콕 = 후보.filter((t) => !가진것.length || 가진것.some((x) => String(x).includes(t)));
  const list = 콕.length
    ? `이번 일에 쓸 도구: **${콕.join(", ")}**` + ''
    : (가진것.length ? `지금 네가 쓸 수 있는 도구: ${가진것.join(", ")}` : '먼저 네 도구 목록에 그런 도구가 있는지 확인해.');
  // ★되돌림은 **대화 이력을 안 실어 보낸다**(그래서 싸다). 그러니 원래 요청을 여기 담지 않으면
  //   두뇌는 *무엇을* 하라는지 모른 채 "도구를 안 불렀다"는 말만 듣는다.
  //   실측(2026-08-21 E2E): 요청을 안 담았더니 되돌림 2회가 다 돌고도 도구 호출 0 이고,
  //   답변은 폴더와 무관한 다짐으로 바뀌었다 — **원래 답보다 나빠졌다.**
  const 원래요청 = String(userMessage || '').trim().slice(0, 300);
  return '[시스템 확인]\n'
    + (원래요청 ? `사용자가 방금 부탁한 것: "${원래요청}"\n` : '')
    + `이건 ${갈래 ? `**${갈래}** 처럼 ` : ''}**도구를 불러야 하는 일**이야.\n`
    + '그런데 이번 턴에 **도구를 하나도 부르지 않았어.**\n'
    + `${list}\n`
    + '· **네 샌드박스와 이 도구는 별개야.** 이 도구는 네 프로세스 **밖에서** 자체 허용 체계로 돌아가.\n'
    + '  네 셸·파일 권한이 읽기 전용이어도 **이 도구와는 아무 상관이 없다.**\n'
    + '· 권한을 미리 짐작하지 말고 그냥 불러. 필요하면 사용자에게 허용 요청이 뜬다.\n'
    + '  **부르지 않으면 그 요청조차 안 생긴다** — 사용자가 "허용할게"라고 해도 소용이 없어.\n'
    + '· 그러니 지금 **위 부탁을 실제로 도구로 처리해.** 막히면 그때 막힌 대로 알려주면 돼.\n'
  //   ★shell 도 같다. codex 는 **자기 셸**을 쓰다 막히고 우리 run_shell 로 오지 않는다.
  //     실측(A/B 각 3판): 이 문장 없이 **0/3**, 붙이면 **3/3** 호출.
  //     없을 때 답 = "실행 정책에서 명령이 차단됐습니다"(자기 셸 얘기다).
  //     붙였을 때 = run_shell 호출 → "터미널 실행 권한이 아직 허용되지 않아서… 허용해줘"(허용 요청이 산다).
    + (kind === 'shell'
      ? '· ★**네 자체 셸(bash/PowerShell)을 쓰지 마.** 그건 막혀 있는 게 맞다.\n'
        + '  대신 **auxo 의 run_shell 도구**를 불러라 — 네 프로세스 밖에서 돌고 자물쇠가 다르다.\n'
        + '  "실행이 정책에 막혔다"는 건 **네 셸 얘기**지 run_shell 얘기가 아니다.\n'
      : '')
  //   ★갈래마다 두뇌가 빠지는 구멍이 다르다. 그걸 그 자리에서 막는다.
  //     실측(2026-08-21): 검색은 **되돌림 0/3** — 안 찾아보고 기온·강수확률을 지어내고
  //     **출처 링크까지 만들어 붙였다.** 도구를 아예 안 준 채 물어도 같은 답이 나왔다(=검색한 적 없음).
  //     그래서 검색만은 *"너는 이걸 모른다"* 는 사실을 못박아야 한다.
    + (kind === 'search'
      ? '· **너는 오늘·지금의 일을 모른다.** 날씨·시세·뉴스 같은 건 검색 없이는 알 수 없어.\n'
        + '  검색하지 않고 쓴 수치·출처는 **네가 지어낸 것**이다. 출처 링크를 상상해서 붙이지 마.\n'
      : '')
    + '· PowerShell·터미널 명령을 대신 알려주는 것은 **답이 아니다.** 네가 도구로 해야 해.\n'
    + '· 답은 **사용자에게 하는 말**로 해. 이 [시스템 확인] 자체는 언급하지 마.';
}

/**
 * 사용자에게 붙이는 정직 안내 — **말투를 지킨다.**
 *
 * ★2026-08-21 사고: 이 문장들을 전부 반말로 박아놨다. 사용자가 존댓말을 지정했는데
 *   앞 문장은 존댓말이고 **우리가 붙인 괄호만 반말**이라 대화가 튀었다.
 *   두뇌가 쓴 말이 아니라 **우리 코드가 쓴 말**이라 1층 말투 설정이 닿지 않는 자리였다.
 *   → speech 를 받아서 맞춘다. 안 넘어오면 **존댓말이 기본**이다(처음 만난 사이의 기본값).
 */
function 말끝(speech) {
  return speech === 'casual'
    ? { 못했다: '못했어', 아니다: '아니야', 다시: '다시 해볼까?',
        안걸림: '걸리지 않았어', 안됨: '처리되지 않았어', 틀릴: '틀릴 수 있어' }
    : { 못했다: '못했습니다', 아니다: '아닙니다', 다시: '다시 해볼까요?',
        안걸림: '걸리지 않았습니다', 안됨: '처리되지 않았습니다', 틀릴: '틀릴 수 있습니다' };
}

/** 두 번 시도해도 안 되면 사용자에게 정직하게. 조용히 넘어가면 처음 문제로 되돌아간다. */
function failNotice(claims, speech) {
  const what = claims.length ? claims[0] : '방금 말한 것';
  const ㅁ = 말끝(speech);
  return `\n\n(솔직히 덧붙이면 — "${what}"은(는) 실제로는 ${ㅁ.안됨}. ${ㅁ.다시})`;
}

/**
 * 요청 기준(reason='request')으로 두 번 다 실패했을 때 사용자에게 붙이는 말.
 *
 * ★없으면 안 된다. 특히 **검색**이 그렇다 —
 *   실측(2026-08-21): *"오늘 서울 날씨 검색해서 알려줘"* 에 `web_search` 를 **한 번도 안 부르고**
 *   기온·강수확률을 **지어내고 출처 링크까지 만들어 붙였다**. 도구를 아예 안 준 채 물어도 같은 답이 나온다
 *   = 검색한 적이 없다는 확증. 폴더 건보다 나쁘다 — *"못 한다"* 는 사용자가 알지만 이건 **믿어버린다.**
 *
 * ⚠️ 답을 지우지는 않는다. 판정이 틀렸을 수도 있고, 지우면 사용자가 더 답답하다. **덧붙이기만** 한다.
 */
function requestFailNotice(kind, speech) {
  const ㅁ = 말끝(speech);
  const 말 = {
    search: `이번엔 실제로 검색해보진 ${ㅁ.못했다}. 위 내용은 **확인된 게 ${ㅁ.아니다}** — ${ㅁ.틀릴}.`,
    file: `파일·폴더 쪽은 실제로 처리하지 ${ㅁ.못했다}.`,
    schedule: `알림·예약은 실제로 ${ㅁ.안걸림}.`,
    shell: `실제로 실행하지는 ${ㅁ.못했다}.`,
  }[kind] || `부탁하신 걸 실제로 처리하지는 ${ㅁ.못했다}.`;
  return `\n\n(솔직히 덧붙이면 — ${말} ${ㅁ.다시})`;
}

