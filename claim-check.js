'use strict';
/**
 * claim-check.js — **"했다고 말한 것과 실제로 한 것을 맞춰본다."**
 *
 * ── 왜 만들었나 ─────────────────────────────────────────────────────────
 * 이런 일이 생긴다: 사용자가 "고양이 얘기는 기억에서 지워주세요"라고 하면
 * 에이전트가 **"네, 지웠습니다"** 라고 답하는데 실제로는 안 지워져 있다.
 * 한참 뒤에야 스스로 알아채고 이렇게 말한다 —
 *   "아까 지웠다고 말씀드린 건 대화 안에서만 빼둔 거였고, 실제 기억에서는 지워지지 않았습니다."
 *
 * 근본 원인은 "거짓말"이 아니라 **착각**이다. 두뇌는 자기가 안 했다는 걸 몰랐다.
 *   · 두뇌에게 "지운다"는 두 뜻이 섞여 있다 — ①도구로 저장소에서 없앰 ②자기 안에서 안 쓰기로 함
 *   · 두뇌는 도구 호출도 답변도 **똑같이 글자로** 한다. 중간 단계를 건너뛰어도 흐름이 안 끊긴다
 *   · 도구를 안 불렀을 때 **아무것도 안 돌아온다.** 그 침묵이 실패 신호로 안 느껴진다
 *
 * → 그래서 프롬프트에 "정직해라"를 더 넣어도 안 걸린다. **규칙 위반이 아니라 착각이라서**,
 *   자기가 스스로 볼 수 없는 자리다. 밖에서 짚어주는 수밖에 없다.
 *
 * ── 어떻게 판정하나 ───────────────────────────────────────────────────
 * "도구를 **썼어야 했는지**"는 판정하지 않는다. 그건 코드가 못 한다.
 * 판정 기준은 **두뇌 자신의 말**이다 — "했다"고 주장했는가.
 *
 *   1) 코드가 훑는다(공짜)  완료 어미가 하나도 없으면 그냥 통과. 잡담 턴은 여기서 끝
 *   2) 두뇌가 뽑는다        "이 답변에서 네가 방금 했다고 주장한 행동이 뭐야?"
 *                          ← 의미 판단이라 코드가 못 한다. 그리고 이래야 사용자가
 *                            무슨 MCP를 깔든 상관없다(도구 이름 목록에 안 매임)
 *   3) 코드가 맞춘다(공짜)  이번 턴 도구 호출 장부와 대조
 *
 * ── 한계 (정직하게) ───────────────────────────────────────────────────
 * · **거짓말은 잡고 빠뜨림은 못 잡는다.** 사용자가 지워달랬는데 두뇌가 아무 말 없이
 *   넘어가면 완료 주장이 없어 통과한다. 아픈 건 거짓말 쪽이라 그것부터 막는다.
 * · 두뇌가 자기 주장을 못 알아볼 수 있다(자기 답을 자기가 보는 거라).
 * · 1차 필터가 헛짚으면 2차 호출값이 낭비된다. 대신 넉넉히 잡는다 — 놓치는 쪽이 더 나쁘다.
 */

const storage = require('./storage');

// ── 1차 필터 ────────────────────────────────────────────────────────────
// 완료를 주장하는 한국어 어미. **넉넉하게** 잡는다(놓치는 것보다 넘치는 게 낫다).
// 여기서 넘치는 건 2차(두뇌 판정)가 걸러준다. 여기서 놓치면 **아무도 못 잡는다.**
//
// ★"~해둘게요 / ~할게요" 같은 형태를 빼면 안 된다. 문법상 미래형이지만
//   한국어에서는 **완료 통보**로 쓰인다 — 사용자는 "됐구나"로 받아들인다.
//   실측: codex 가 *"기억해둘게요"* 라 해놓고 아무것도 저장하지 않았는데 이 필터를 통과했다.
// ★"놨어 / 뒀어" 는 앞 동사가 무엇이든 걸리게 둔다("걸어놨어" · "적어뒀어").
// ★"~해봤어요" 형태가 통째로 빠져 있었다. `했어` 는 잡는데 `해봤어` 는 못 잡았다 —
//   같은 뜻인데 한쪽만 걸렸다. 실측: *"확인해봤어요"* 라며 조회 도구를 안 부르고 목록을 지어낸
//   답변이 검사를 통과했다. 조회·확인 계열에서 가장 흔한 말투다.
const DONE_HINT = /(했어|했습니다|했다|했네|해뒀|해놨|해둠|해둘|해놓|뒀어|뒀습니다|뒀네|놨어|놨습니다|봤어|봤습니다|봤다|보니|났어|됐어|됐습니다|됐네|완료|저장|지웠|지울게|삭제했|삭제할게|보냈|보냈습니다|보낼게|등록했|등록할게|예약했|예약할게|만들었|만들게|설치했|기억했|기억할게|반영했|고쳐|고칠게|정리했|적었|적어둘게|넣었|드렸|끝냈|마쳤|올렸)/;

/** 이 답변이 검사할 가치가 있나. 없으면 두뇌를 부르지 않는다(비용 0). */
function mayClaimCompletion(text) {
  const s = String(text || '');
  // ★길이로 거르지 않는다. **가장 위험한 거짓말이 가장 짧다** —
  //   "삭제했어요."(6자)가 길이 8 제한에 걸려 통째로 통과하고 있었다(실측).
  //   패턴에 안 걸리면 어차피 여기서 끝나므로, 길이 제한은 비용을 아껴주지도 않았다.
  if (!s.trim()) return false;
  return DONE_HINT.test(s);
}

// ── 2차: 두뇌에게 주장 뽑기 ──────────────────────────────────────────────
// ★"~할게요"를 여기서도 골라야 한다. 1차 DONE_HINT 에는 넣어 놓고 이 프롬프트엔 안 넣었더니
//   **1차가 잡은 걸 2차가 버렸다** — 우리 코드 안에서 두 규칙이 서로 반대였다.
//   실측(2026-08-14): codex 가 *"기억해둘게요"* 라 해놓고 remember 를 안 불렀는데,
//   여기서 `[]` 를 돌려줘 검사가 조용히 통과했다(원인 = 아래 '고르지 말 것'의 "앞으로 할 일" 조항).
const EXTRACT_SYSTEM = `너는 답변에서 **"내가 방금 해냈다"고 주장한 행동**만 골라내는 검사기야.

고를 것 — 답변한 사람이 **자기가 방금 실제로 수행했다**고 말한 것
  "기억에서 지웠어" / "저장해뒀어" / "파일 만들었어" / "메시지 보냈어" / "예약해뒀어"

  ★한국어에서는 **"~해둘게요 / ~할게요 / ~해놓을게"도 완료 통보다.**
    문법만 미래형일 뿐, 사용자는 "됐구나"로 받아들이고 다시 확인하지 않는다.
    **사용자가 방금 부탁한 그 일**을 이렇게 답했으면 반드시 골라라.
      "기억해둬"   → "기억해둘게요"    ← 고른다
      "알림 걸어줘" → "걸어놓을게요"    ← 고른다

고르지 말 것
  · 제안·질문      "지울까?" "만들어 드릴까요?"
  · 설명·안내      "이렇게 하면 지워집니다"
  · **다음번** 습관  "다음엔 그렇게 할게" / "앞으로는 미리 알려드릴게요"
                  ← 지금 부탁받은 일이 아니라 **나중 행동**을 말하는 것만 여기 해당한다.
                    지금 부탁받은 일을 "~할게"로 답한 것은 위에서 골라야 한다.
  · 생각·의견·요약·감정 — 도구 없이 말만으로 되는 것 전부
  · 답변 자체(설명·번역·계산)는 행동이 아니다

출력: JSON 배열만. 각 항목은 짧은 한 줄.
없으면 [] 만 내. 다른 말 절대 금지.
예) ["기억에서 고양이 삭제"]`;

/** 답변에서 완료 주장 목록을 뽑는다. 실패하면 빈 배열(검사가 대화를 막지 않는다). */
async function extractClaims(responseText, generate) {
  let raw;
  try {
    raw = await generate(EXTRACT_SYSTEM, `[답변]\n${String(responseText).slice(0, 3000)}\n\n완료 주장만 JSON 배열로.`,
      { timeout: 30000, temperature: 0 });
  } catch (_) { return []; }
  const m = String(raw || '').match(/\[[\s\S]*\]/);
  if (!m) return [];
  try {
    const arr = JSON.parse(m[0]);
    return Array.isArray(arr) ? arr.map(x => String(x || '').trim()).filter(Boolean).slice(0, 8) : [];
  } catch (_) { return []; }
}

// ── 3차: 대조 ───────────────────────────────────────────────────────────
/**
 * @returns {Promise<{suspect:boolean, claims:string[], calledTools:string[]}>}
 *   suspect=true 면 "말은 했는데 도구를 하나도 안 불렀다".
 */
async function check({ agentId, responseText, turnStartTs, generate }) {
  const empty = { suspect: false, claims: [], calledTools: [] };
  if (!agentId || !responseText || typeof generate !== 'function') return empty;

  // 1차 — 공짜
  if (!mayClaimCompletion(responseText)) return empty;

  // 3차 재료를 먼저 읽는다(공짜). 도구를 이미 불렀으면 2차(유료)를 건너뛴다.
  //   ※ 도구를 하나라도 불렀다면 대개 정상이고, 어느 도구가 어느 주장에 대응하는지까지
  //     따지려면 또 두뇌가 필요하다. 지금은 **아무것도 안 부르고 했다고 하는 것**만 잡는다.
  let called = [];
  try { called = storage.toolCallsSince(agentId, turnStartTs) || []; } catch (_) { called = []; }
  if (called.length) return { suspect: false, claims: [], calledTools: called };

  // 2차 — 유료
  const claims = await extractClaims(responseText, generate);
  if (!claims.length) return { suspect: false, claims: [], calledTools: called };

  return { suspect: true, claims, calledTools: called };
}

// ── 되돌림 문구 ─────────────────────────────────────────────────────────
/**
 * 두뇌에게 돌려줄 말. **"안 했어"만으로는 부족하다** — 도구가 아예 없는 상황이면
 * 두뇌는 또 말로 때운다. 그래서 두 가지를 반드시 같이 준다.
 *   ① 지금 쓸 수 있는 도구가 무엇인지 (또는 목록을 확인하라는 지시)
 *   ② **"없으면 못 한다고 말해도 된다"** — 이게 없으면 어떻게든 되려고 하다 또 지어낸다
 *
 * @param toolNames 우리가 넘긴 도구 이름들. 구독 두뇌는 CLI가 노출을 정해서 우리가 모른다
 *                  → 빈 배열이면 "네 목록을 확인하라"로 바꿔 말한다(그 답이 배선 끊김도 드러낸다).
 */
function buildNudge(claims, toolNames = []) {
  const list = Array.isArray(toolNames) && toolNames.length
    ? `지금 네가 쓸 수 있는 도구: ${toolNames.join(', ')}`
    : '먼저 네 도구 목록에 그런 도구가 있는지 확인해.';
  return '[시스템 확인]\n'
    + `방금 답에서 이걸 **해냈다고** 말했어: ${claims.map(c => `"${c}"`).join(', ')}\n`
    + '그런데 이번 턴에 **도구를 하나도 부르지 않았어.** 말로만 처리한 거야.\n'
    + `${list}\n`
    + '· 그 도구가 있으면 **지금 실제로 불러서** 하고, 그다음에 답해.\n'
    + '· 없으면 **"못 한다"고 사용자에게 솔직히 말해.** 못 하는 건 괜찮아. 한 척하는 게 문제야.\n'
    + '· 이 [시스템 확인] 자체는 사용자에게 언급하지 마.';
}

/** 두 번 시도해도 안 되면 사용자에게 정직하게. 조용히 넘어가면 처음 문제로 되돌아간다. */
function failNotice(claims) {
  const what = claims.length ? claims[0] : '방금 말한 것';
  return `\n\n(솔직히 덧붙이면 — "${what}"은(는) 실제로는 처리되지 않았어. 다시 해볼까?)`;
}

module.exports = { mayClaimCompletion, extractClaims, check, buildNudge, failNotice, DONE_HINT };
