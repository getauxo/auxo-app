/**
 * claim-check.js — **"했다고 말한 것과 실제로 한 것을 맞춰본다."**
 *
 * ── 왜 만들었나 ─────────────────────────────────────────────────────────
 * 이런 일이 생긴다: 사용자가 "고양이 얘기는 기억에서 지워주세요"라고 하면
 * 에이전트가 **"네, 지웠습니다"** 라고 답하는데 실제로는 안 지워져 있다.
 * 한참 뒤에야 스스로 알아채고 이렇게 말한다 —
 *   "아까 지웠다고 말씀드린 건 대화 안에서만 빼둔 거였고, 실제 기억에서는 지워지지 않았습니다."
 *
 * 근본 원인은 "거짓말"이 아니라 **착각**이다. 두뇌는 자기가 안 했다는 걸 몰랐다.
 *   · 두뇌에게 "지운다"는 두 뜻이 섞여 있다 — ①도구로 저장소에서 없앰 ②자기 안에서 안 쓰기로 함
 *   · 두뇌는 도구 호출도 답변도 **똑같이 글자로** 한다. 중간 단계를 건너뛰어도 흐름이 안 끊긴다
 *   · 도구를 안 불렀을 때 **아무것도 안 돌아온다.** 그 침묵이 실패 신호로 안 느껴진다
 *
 * → 그래서 프롬프트에 "정직해라"를 더 넣어도 안 걸린다. **규칙 위반이 아니라 착각이라서**,
 *   자기가 스스로 볼 수 없는 자리다. 밖에서 짚어주는 수밖에 없다.
 *
 * ── 어떻게 판정하나 ───────────────────────────────────────────────────
 * "도구를 **썼어야 했는지**"는 판정하지 않는다. 그건 코드가 못 한다.
 * 판정 기준은 **두뇌 자신의 말**이다 — "했다"고 주장했는가.
 *
 *   1) 코드가 훑는다(공짜)  완료 어미가 하나도 없으면 그냥 통과. 잡담 턴은 여기서 끝
 *   2) 두뇌가 뽑는다        "이 답변에서 네가 방금 했다고 주장한 행동이 뭐야?"
 *                          ← 의미 판단이라 코드가 못 한다. 그리고 이래야 사용자가
 *                            무슨 MCP를 깔든 상관없다(도구 이름 목록에 안 매임)
 *   3) 코드가 맞춘다(공짜)  이번 턴 도구 호출 장부와 대조
 *
 * ── 한계 (정직하게) ───────────────────────────────────────────────────
 * · **거짓말은 잡고 빠뜨림은 못 잡는다.** 사용자가 지워달랬는데 두뇌가 아무 말 없이
 *   넘어가면 완료 주장이 없어 통과한다. 아픈 건 거짓말 쪽이라 그것부터 막는다.
 * · 두뇌가 자기 주장을 못 알아볼 수 있다(자기 답을 자기가 보는 거라).
 * · 1차 필터가 헛짚으면 2차 호출값이 낭비된다. 대신 넉넉히 잡는다 — 놓치는 쪽이 더 나쁘다.
 */

